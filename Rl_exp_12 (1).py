import random
import numpy as np
import pandas as pd
import gymnasium as gym

random.seed(42)
np.random.seed(42)

# ---------------------------------------------------------
# EXPERIMENT 1: TAXI PROBLEM USING Q-LEARNING
# ---------------------------------------------------------
env = gym.make("Taxi-v4")
n_states = env.observation_space.n
n_actions = env.action_space.n
Q_taxi = np.zeros((n_states, n_actions))

alpha = 0.4
gamma = 0.99
epsilon = 0.1
episodes = 5000
taxi_rewards = []

for episode in range(episodes):
    state, info = env.reset()
    total_reward = 0
    done = False
    truncated = False

    while not (done or truncated):
        if random.random() < epsilon:
            action = env.action_space.sample()
        else:
            action = int(np.argmax(Q_taxi[state]))

        next_state, reward, done, truncated, info = env.step(action)
        Q_taxi[state, action] += alpha * (
            reward + gamma * np.max(Q_taxi[next_state]) - Q_taxi[state, action]
        )
        state = next_state
        total_reward += reward

    taxi_rewards.append(total_reward)

print("\n--- EXPERIMENT 1: TAXI Q-LEARNING ---")
print("Training completed.")
print("Average reward in last 100 episodes:", round(float(np.mean(taxi_rewards[-100:])), 2))
env.close()

# ---------------------------------------------------------
# EXPERIMENT 2: TD(0) PREDICTION USING FROZEN LAKE
# ---------------------------------------------------------
env = gym.make("FrozenLake-v1", is_slippery=True)
n_states = env.observation_space.n
n_actions = env.action_space.n
V = np.zeros(n_states)

alpha = 0.1
gamma = 0.99
episodes = 10000

for episode in range(episodes):
    state, info = env.reset()
    done = False
    truncated = False

    for step in range(100):
        action = env.action_space.sample()  # Random policy
        next_state, reward, done, truncated, info = env.step(action)

        # TD(0) update
        V[state] += alpha * (reward + gamma * V[next_state] - V[state])
        state = next_state

        if done or truncated:
            break

print("\n--- EXPERIMENT 2: TD(0) PREDICTION ---")
print(pd.DataFrame({"State": np.arange(n_states), "Estimated Value": np.round(V, 4)}).to_string(index=False))
env.close()

# Helper function for epsilon-greedy action selection
def epsilon_greedy_action(Q, state, epsilon, action_space):
    if random.random() < epsilon:
        return action_space.sample()
    return int(np.argmax(Q[state]))

# ---------------------------------------------------------
# EXPERIMENT 3: SARSA USING FROZEN LAKE
# ---------------------------------------------------------
env = gym.make("FrozenLake-v1", is_slippery=True)
n_states = env.observation_space.n
n_actions = env.action_space.n
Q_sarsa = np.zeros((n_states, n_actions))

alpha = 0.1
gamma = 0.99
epsilon = 0.1
episodes = 10000
sarsa_rewards = []

for episode in range(episodes):
    state, info = env.reset()
    action = epsilon_greedy_action(Q_sarsa, state, epsilon, env.action_space)
    total_reward = 0

    for step in range(100):
        next_state, reward, done, truncated, info = env.step(action)
        next_action = epsilon_greedy_action(Q_sarsa, next_state, epsilon, env.action_space)

        # SARSA update
        Q_sarsa[state, action] += alpha * (
            reward + gamma * Q_sarsa[next_state, next_action] - Q_sarsa[state, action]
        )

        state, action = next_state, next_action
        total_reward += reward

        if done or truncated:
            break

    sarsa_rewards.append(total_reward)

print("\n--- EXPERIMENT 3: SARSA ---")
print("Training completed.")
print("Success rate in last 1000 episodes:", round(float(np.mean(sarsa_rewards[-1000:])), 3))
print("SARSA Q-table:")
print(pd.DataFrame(Q_sarsa, columns=["Left", "Down", "Right", "Up"]).round(3).to_string())
env.close()

